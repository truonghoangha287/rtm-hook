"""Render RTM views and lay them out over the index + generated section files.

Index (rtm.index)        hand-written sections + marker blocks (summary, toc, views without a file)
Section files (rtm.dir)  one file per view, or one file per ID-range shard when a view is large:
    <rtm.dir>/forward-br.md
    <rtm.dir>/coverage-ac/STORY-001-050.md

Every generated region sits between markers; `sha` lets `check` detect hand edits:
    <!-- rtm:begin forward-br sha=0123456789 -->  …  <!-- rtm:end forward-br -->
"""
from __future__ import annotations

import hashlib
import os
import re
from collections import deque
from dataclasses import dataclass, field

from .checks import Finding
from .config import Config
from .graph import Graph
from .ids import split_key

BLOCK = re.compile(r"<!-- rtm:begin (\S+)(?: sha=(\w+))? -->\n(.*?)<!-- rtm:end \1 -->", re.S)
GEN_HEADER = "<!-- rtm:generated by `rtm sync` from rtm.config.json — do not edit; change the source artifacts -->"
INDEX_TYPES = ("summary", "toc")


def sha(body: str) -> str:
    return hashlib.sha256(body.encode()).hexdigest()[:10]


@dataclass
class Span:
    id: str
    start: int
    end: int
    body: str
    recorded: str | None


def blocks(text: str) -> dict[str, Span]:
    return {m.group(1): Span(m.group(1), m.start(), m.end(), m.group(3), m.group(2))
            for m in BLOCK.finditer(text)}


def edited_blocks(text: str) -> list[str]:
    return [b.id for b in blocks(text).values() if b.recorded and b.recorded != sha(b.body)]


def wrap(bid: str, body: str) -> str:
    return f"<!-- rtm:begin {bid} sha={sha(body)} -->\n{body}<!-- rtm:end {bid} -->"


def splice(text: str, rendered: dict[str, str], titles: dict[str, str]) -> tuple[str, dict]:
    """Replace block bodies in text; append missing blocks. Returns (text, {bid: (+rows, -rows)})."""
    current = blocks(text)
    changes: dict[str, tuple[int, int]] = {}
    out, pos = [], 0
    for span in sorted(current.values(), key=lambda s: s.start):
        if span.id not in rendered:
            continue
        out.append(text[pos:span.start])
        out.append(wrap(span.id, rendered[span.id]))
        pos = span.end
        changes[span.id] = row_delta(span.body, rendered[span.id])
    out.append(text[pos:])
    new = "".join(out)
    for bid, body in rendered.items():
        if bid not in current:
            new = new.rstrip("\n") + f"\n\n## {titles.get(bid, bid)}\n\n{wrap(bid, body)}\n"
            changes[bid] = row_delta("", body)
    return new, {k: v for k, v in changes.items() if v != (0, 0)}


def rows_of(s: str) -> set[str]:
    return {l for l in s.splitlines() if l.startswith("|") and not l.startswith("|---")}


def row_delta(old: str, new: str) -> tuple[int, int]:
    a, b = rows_of(old), rows_of(new)
    return len(b - a), len(a - b)


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ") or "—"


def table_md(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


# -- views ---------------------------------------------------------------------------
def step_descendants(cfg: Config, root: str) -> set[str]:
    down: dict[str, set[str]] = {}
    for l in cfg.layers.values():
        for p in l.trace_via:
            if p != l.id:
                down.setdefault(p, set()).add(l.id)
    seen, q = set(), deque([root])
    while q:
        for c in down.get(q.popleft(), ()):
            if c not in seen:
                seen.add(c)
                q.append(c)
    return seen


def auto_views(cfg: Config) -> list[dict]:
    L, order = cfg.layers, cfg.order
    roots = [s for s in order if L[s].kind == "ids" and not L[s].parent
             and not [u for u in L[s].upstream if u != s]]
    views = []
    for r in roots:
        desc = step_descendants(cfg, r)
        cols = [s for s in order if s in desc and not L[s].parent]
        if cols:
            chain = " → ".join([L[r].label] + [L[c].label for c in cols])
            views.append({"id": f"forward-{r}", "type": "forward", "root": r, "columns": cols,
                          "title": f"Forward traceability — {chain}"})
    for s in order:
        if len([g for g in L[s].require if any(not x.startswith("@") for x in g)]) >= 2:
            need = " + ".join(L[g[0]].label for g in L[s].require if not g[0].startswith("@"))
            views.append({"id": f"justify-{s}", "type": "justify", "layer": s,
                          "title": f"{L[s].label} justification — each cites {need}"})
    for s in order:
        ch = L[s].children
        if not ch:
            continue
        target = next((c["to"] for c in cfg.coverage if c["from"] == ch.id), None)
        if not target:
            desc = step_descendants(cfg, ch.id)
            target = next((x for x in reversed(order) if x in desc), None)
        if target:
            views.append({"id": f"coverage-{ch.id}", "type": "children", "parent": s, "target": target,
                          "title": f"{ch.label} → {L[target].label} coverage"})
    last = order[-1]
    if roots and last not in roots:
        views.append({"id": f"backward-{last}", "type": "backward", "layer": last, "up": roots,
                      "title": f"Backward traceability — {L[last].label} → need"})
    views.append({"id": "summary", "type": "summary", "title": "Coverage summary"})
    views.append({"id": "toc", "type": "toc", "title": "Matrix sections"})
    return views


def resolve_views(cfg: Config) -> list[dict]:
    raw = cfg.views_raw
    if raw == "auto":
        views = auto_views(cfg)
    elif isinstance(raw, list):
        views = [dict(v) for v in raw]
    elif isinstance(raw, dict):
        drop = set(raw.get("drop", []))
        views = [v for v in auto_views(cfg) if v["id"] not in drop] if raw.get("auto", True) else []
        for extra in (dict(v) for v in raw.get("add", [])):  # after the last view of its type
            same = [i for i, v in enumerate(views) if v["type"] == extra["type"]]
            at = same[-1] + 1 if same else next(
                (i for i, v in enumerate(views) if v["type"] in INDEX_TYPES), len(views))
            views.insert(at, extra)
    else:
        raise ValueError("views must be 'auto', a list, or {auto, add, drop}")
    for v in views:
        if v["type"] not in INDEX_TYPES and "file" not in v and cfg.rtm_dir:
            v["file"] = v["id"]  # one file (or shard dir) per view under rtm.dir
        if "shard_size" not in v:
            v["shard_size"] = cfg.shard_size
    return views


@dataclass
class Table:
    header: list[str]
    rows: list[tuple[str, list[str]]]  # (row key, cells)
    note: str = ""


@dataclass
class Output:
    index_blocks: dict[str, str] = field(default_factory=dict)
    titles: dict[str, str] = field(default_factory=dict)
    files: dict[str, str] = field(default_factory=dict)  # rel path -> full content
    toc: list[tuple[str, str, int]] = field(default_factory=list)  # (title, rel path, rows)


class Renderer:
    def __init__(self, g: Graph, findings: list[Finding]):
        self.g, self.cfg, self.findings = g, g.cfg, findings

    # -- layout ---------------------------------------------------------------------
    def all(self) -> Output:
        out = Output()
        views = resolve_views(self.cfg)
        toc_view = None
        for v in views:
            if v["type"] == "toc":
                toc_view = v
                continue
            fn = getattr(self, "_" + v["type"], None)
            if fn is None:
                raise ValueError(f"view '{v['id']}': unknown type '{v['type']}'")
            t = fn(v)
            title = v.get("title", v["id"])
            if v.get("file") and self.cfg.rtm_dir:
                self._files(v, title, t, out)
            else:
                out.index_blocks[v["id"]] = self._body(t)
                out.titles[v["id"]] = title
        if toc_view and out.toc:
            out.index_blocks["toc"] = self._body(Table(
                ["Section", "File", "Rows"],
                [(p, [t, f"[{os.path.relpath(p, os.path.dirname(self.cfg.rtm))}]"
                         f"({os.path.relpath(p, os.path.dirname(self.cfg.rtm))})", str(n)])
                 for t, p, n in out.toc]))
            out.titles["toc"] = toc_view.get("title", "Matrix sections")
        return out

    def _body(self, t: Table) -> str:
        return ("<!-- generated — edit the source artifacts, not this block -->\n"
                + table_md(t.header, [c for _, c in t.rows]) + (f"\n{t.note}\n" if t.note else ""))

    def _files(self, v: dict, title: str, t: Table, out: Output) -> None:
        base = f"{self.cfg.rtm_dir}/{v['file']}"
        size = int(v.get("shard_size") or 0)
        if not size or len(t.rows) <= size:
            groups = {"": t.rows}
        else:
            groups = {}
            for k, cells in t.rows:
                groups.setdefault(self._shard(k, size), []).append((k, cells))
        for name, rows in groups.items():
            path = f"{base}.md" if not name else f"{base}/{name}.md"
            bid = v["id"] if not name else f"{v['id']}:{name}"
            sub = Table(t.header, rows, t.note if not name else "")
            index_rel = os.path.relpath(self.cfg.rtm, os.path.dirname(path))
            part = f" — {name}" if name else ""
            out.files[path] = (f"{GEN_HEADER}\n# {title}{part}\n\n[← RTM index]({index_rel})\n\n"
                               f"{wrap(bid, self._body(sub))}\n")
            out.toc.append((title + part, path, len(rows)))

    def _shard(self, k: str, size: int) -> str:
        n = self.g.nodes.get(k)
        if n and self.cfg.layers[n.layer].kind == "files":
            c = (n.label[:1] or "_").upper()
            return c if c.isalnum() else "_"
        p, num = split_key(k.partition("/")[0])
        lo = (num - 1) // size * size + 1
        w = self.g.syntax.width.get(p, 3)
        return f"{p}-{lo:0{w}d}-{lo + size - 1:0{w}d}"

    # -- helpers --------------------------------------------------------------------
    def _list(self, layer: str, keys: list[str]) -> str:
        if not keys:
            return "—"
        if layer in self.cfg.count_only:
            return f"{len(keys)} file" + ("s" if len(keys) != 1 else "")
        shown = [self.g.show(k) for k in keys[: self.cfg.max_list]]
        more = len(keys) - len(shown)
        return ", ".join(shown) + (f" (+{more})" if more else "")

    def _status(self, desc: dict[str, list[str]], cols: list[str]) -> str:
        status = self.cfg.status.get("initial", "Open")
        for c in cols:
            if not desc.get(c):
                break
            status = self.cfg.status.get(c, self.cfg.layers[c].label)
        return status

    # -- view types -----------------------------------------------------------------
    def _forward(self, v: dict) -> Table:
        root, cols = v["root"], v["columns"]
        nodes = [n for n in self.g.layer_nodes(root)
                 if not v.get("prefix") or n.key.startswith(v["prefix"] + "-")]
        show_src = any(self.g.source(n) for n in nodes)
        header = [v.get("prefix") or self.cfg.layers[root].label] + (["Source"] if show_src else [])
        header += [self.cfg.layers[c].label for c in cols]
        header.append("Status" if self.cfg.status else "Reached")
        rows = []
        for n in nodes:
            d = self.g.descendants(n.key)
            cells = [self.g.show(n.key)] + ([self.g.source(n)] if show_src else [])
            cells += [self._list(c, d.get(c, [])) for c in cols]
            rows.append((n.key, cells + [self._status(d, cols)]))
        note = "Reached = furthest step with at least one linked item, stopping at the first gap."
        return Table(header, rows, note)

    def _justify(self, v: dict) -> Table:
        layer = self.cfg.layers[v["layer"]]
        groups = [g for g in layer.require if any(not x.startswith("@") for x in g)]
        header = [layer.label] + [" / ".join(self.cfg.layers[x].label for x in g if not x.startswith("@"))
                                  for g in groups] + ["OK"]
        rows = []
        for n in self.g.layer_nodes(layer.id):
            cells, ok = [], True
            for g in groups:
                ks = sorted({k for x in g if not x.startswith("@")
                             for k in n.refs.get(x, ()) if k in self.g.nodes}, key=self.g.show)
                ok &= bool(ks)
                cells.append(", ".join(self.g.show(k) for k in ks) or "—")
            rows.append((n.key, [self.g.show(n.key)] + cells + ["✓" if ok else "✗"]))
        return Table(header, rows)

    def _children(self, v: dict) -> Table:
        parent = self.cfg.layers[v["parent"]]
        child, target = parent.children.id, v["target"]
        header = [parent.label, "Traces", f"{parent.children.label} covered", "Uncovered",
                  self.cfg.layers[target].label]
        rows = []
        for p in self.g.layer_nodes(parent.id):
            kids = sorted((k for k in self.g.down.get(p.key, ()) if self.g.nodes[k].layer == child),
                          key=lambda k: self.g.syntax.show(k))
            covered, tests = [], set()
            for k in kids:
                t = self.g.descendants(k).get(target, [])
                if t:
                    covered.append(k)
                    tests.update(t)
            traces = sorted({k for l in parent.upstream for k in p.refs.get(l, ()) if k in self.g.nodes},
                            key=self.g.show)
            rows.append((p.key, [self.g.show(p.key), ", ".join(self.g.show(k) for k in traces),
                                 f"{len(covered)}/{len(kids)}",
                                 ", ".join(self.g.show(k).split("/")[-1] for k in kids if k not in covered),
                                 self._list(target, sorted(tests))]))
        return Table(header, rows)

    def _backward(self, v: dict) -> Table:
        layer = self.cfg.layers[v["layer"]]
        up = v.get("up", [])
        header = [layer.label, "Traces to"] + [f"↑ {self.cfg.layers[u].label}" for u in up] + ["↑ Source"]
        rows, untraced = [], 0
        for n in self.g.layer_nodes(layer.id):
            direct = sorted(self.g.parents(n), key=self.g.show)
            if not direct:
                untraced += 1
                continue
            anc = self.g.ancestors(n.key)
            srcs = sorted({self.g.source(self.g.nodes[k]) for u in up for k in anc.get(u, [])} - {""})
            rows.append((n.key, [self.g.show(n.key), ", ".join(self.g.show(k) for k in direct)]
                         + [self._list(u, anc.get(u, [])) for u in up] + ["; ".join(srcs) or "—"]))
        hint = f"`{layer.ref_marker}` line" if layer.ref_marker else "upstream reference"
        note = f"{untraced} {layer.label} item(s) have no {hint} yet and are not listed." if untraced else ""
        return Table(header, rows, note)

    def _summary(self, v: dict) -> Table:
        rows = []
        missing = {f.subject for f in self.findings if f.rule == "MISSING-UPSTREAM"}
        for lid in self.cfg.order:
            layer, nodes = self.cfg.layers[lid], self.g.layer_nodes(lid)
            if layer.require:
                ok = sum(1 for n in nodes if n.key not in missing)
                rows.append((lid, [f"{layer.label} with required upstream links", f"{ok} / {len(nodes)}"]))
            else:
                rows.append((lid, [f"{layer.label} defined", str(len(nodes))]))
        for c in self.cfg.coverage:
            nodes = self.g.layer_nodes(c["from"])
            hit = sum(1 for n in nodes if self.g.descendants(n.key).get(c["to"]))
            rows.append((c["from"], [f"{self.cfg.layers[c['from']].label} reaching ≥ 1 "
                                     f"{self.cfg.layers[c['to']].label}", f"{hit} / {len(nodes)}"]))
        counts = [sum(1 for f in self.findings if f.severity == s) for s in ("P0", "P1", "P2", "P3")]
        rows.append(("", ["Findings (P0 / P1 / P2 / P3)", " / ".join(map(str, counts))]))
        return Table(["Check", "Result"], rows,
                     "Ask with `rtm.py why <ID>` / `rtm.py query …`; itemised findings: `rtm.py check`.")
