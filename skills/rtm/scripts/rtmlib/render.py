"""Render generated RTM blocks and splice them into rtm.md between markers.

    <!-- rtm:begin forward-br sha=0123456789 -->
    ...generated, do not edit...
    <!-- rtm:end forward-br -->

Only text between markers is ever rewritten. `sha` lets `check` detect hand edits.
"""
from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass

from .checks import Finding
from .graph import Graph

BLOCK = re.compile(r"<!-- rtm:begin (\S+)(?: sha=(\w+))? -->\n(.*?)<!-- rtm:end \1 -->", re.S)

DEFAULT_TITLES = {
    "forward": "Forward traceability",
    "justify": "Upstream justification",
    "children": "Acceptance-criteria coverage",
    "backward": "Backward traceability (test → need)",
    "summary": "Coverage summary",
}


def sha(body: str) -> str:
    return hashlib.sha256(body.encode()).hexdigest()[:10]


@dataclass
class Span:
    id: str
    start: int
    end: int
    body: str
    recorded: str | None


def blocks(text: str) -> dict[str, Span]:
    return {m.group(1): Span(m.group(1), m.start(), m.end(), m.group(3), m.group(2))
            for m in BLOCK.finditer(text)}


def edited_blocks(text: str) -> list[str]:
    return [b.id for b in blocks(text).values() if b.recorded and b.recorded != sha(b.body)]


def wrap(bid: str, body: str) -> str:
    return f"<!-- rtm:begin {bid} sha={sha(body)} -->\n{body}<!-- rtm:end {bid} -->"


def splice(text: str, rendered: dict[str, str], titles: dict[str, str]) -> tuple[str, dict]:
    """Replace each block body; append missing blocks at the end. Returns (text, changes)."""
    current = blocks(text)
    changes: dict[str, tuple[int, int]] = {}
    out, pos = [], 0
    for span in sorted(current.values(), key=lambda s: s.start):
        if span.id not in rendered:
            continue
        out.append(text[pos:span.start])
        out.append(wrap(span.id, rendered[span.id]))
        pos = span.end
        changes[span.id] = _row_delta(span.body, rendered[span.id])
    out.append(text[pos:])
    new = "".join(out)
    for bid, body in rendered.items():
        if bid not in current:
            new = new.rstrip("\n") + f"\n\n## {titles.get(bid, bid)}\n\n{wrap(bid, body)}\n"
            changes[bid] = _row_delta("", body)
    return new, {k: v for k, v in changes.items() if v != (0, 0)}


def _row_delta(old: str, new: str) -> tuple[int, int]:
    rows = lambda s: {l for l in s.splitlines() if l.startswith("|") and not l.startswith("|---")}
    a, b = rows(old), rows(new)
    return len(b - a), len(a - b)


# -- table helpers -----------------------------------------------------------------
def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ") or "—"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


class Renderer:
    def __init__(self, g: Graph, findings: list[Finding]):
        self.g = g
        self.cfg = g.cfg
        self.r = g.cfg.render
        self.findings = findings
        self.max_list = int(self.r.get("max_list", 6))
        self.count_only = set(self.r.get("count_only", []))

    def all(self) -> tuple[dict[str, str], dict[str, str]]:
        bodies, titles = {}, {}
        for b in self.r.get("blocks", []):
            fn = getattr(self, "_" + b["type"])
            bodies[b["id"]] = "<!-- generated by rtm sync — edit the source artifacts, not this block -->\n" + fn(b)
            titles[b["id"]] = b.get("title", DEFAULT_TITLES.get(b["type"], b["id"]))
        return bodies, titles

    def _list(self, layer: str, keys: list[str]) -> str:
        if not keys:
            return "—"
        if layer in self.count_only:
            return f"{len(keys)} file" + ("s" if len(keys) != 1 else "")
        shown = [self.g.show(k) for k in keys[: self.max_list]]
        more = len(keys) - len(shown)
        return ", ".join(shown) + (f" (+{more})" if more else "")

    def _status(self, desc: dict[str, list[str]], cols: list[str]) -> str:
        stages = self.r.get("stages", {})
        status = self.r.get("initial_status", "Open")
        for c in cols:
            if c not in stages:
                continue
            if not desc.get(c):
                break
            status = stages[c]
        return status

    # -- block types --------------------------------------------------------------
    def _forward(self, b: dict) -> str:
        root, cols = b["root"], b["columns"]
        nodes = [n for n in self.g.layer_nodes(root)
                 if not b.get("prefix") or n.key.startswith(b["prefix"] + "-")]
        show_src = any(self.g.source(n) for n in nodes)
        header = [self.cfg.layers[root].label if not b.get("prefix") else b["prefix"]]
        header += (["Source"] if show_src else [])
        header += [self.cfg.layers[c].label for c in cols] + ["Status"]
        rows = []
        for n in nodes:
            d = self.g.descendants(n.key)
            row = [self.g.show(n.key)] + ([self.g.source(n)] if show_src else [])
            row += [self._list(c, d.get(c, [])) for c in cols]
            rows.append(row + [self._status(d, cols)])
        legend = " → ".join(self.r.get("stages", {}).values())
        return table(header, rows) + (f"\nStatus = furthest stage reached without a gap: Open → {legend}.\n"
                                      if legend else "")

    def _justify(self, b: dict) -> str:
        layer = self.cfg.layers[b["layer"]]
        groups = layer.require
        header = [layer.label] + [" / ".join(self.cfg.layers[x].label for x in grp if not x.startswith("@"))
                                  for grp in groups] + ["OK"]
        rows = []
        for n in self.g.layer_nodes(layer.id):
            cells, ok = [], True
            for grp in groups:
                ks = sorted({k for x in grp if not x.startswith("@")
                             for k in n.refs.get(x, ()) if k in self.g.nodes},
                            key=lambda k: self.g.show(k))
                ok &= bool(ks)
                cells.append(", ".join(self.g.show(k) for k in ks) or "—")
            rows.append([self.g.show(n.key)] + cells + ["✓" if ok else "✗"])
        return table(header, rows)

    def _children(self, b: dict) -> str:
        parent = self.cfg.layers[b["parent"]]
        child, target = parent.children.id, b["target"]
        up = parent.upstream
        header = [parent.label, "Traces", f"{parent.children.label} covered", "Uncovered",
                  self.cfg.layers[target].label]
        rows = []
        for p in self.g.layer_nodes(parent.id):
            kids = sorted(self.g.down.get(p.key, ()), key=lambda k: self.g.show(k))
            kids = [k for k in kids if self.g.nodes[k].layer == child]
            covered, tests = [], set()
            for k in kids:
                t = self.g.descendants(k).get(target, [])
                if t:
                    covered.append(k)
                    tests.update(t)
            traces = sorted({k for l in up for k in p.refs.get(l, ()) if k in self.g.nodes},
                            key=lambda k: self.g.show(k))
            uncovered = [self.g.show(k).split("/")[-1] for k in kids if k not in covered]
            rows.append([self.g.show(p.key), ", ".join(self.g.show(k) for k in traces),
                         f"{len(covered)}/{len(kids)}", ", ".join(uncovered),
                         self._list(target, sorted(tests))])
        return table(header, rows)

    def _backward(self, b: dict) -> str:
        layer = self.cfg.layers[b["layer"]]
        up = b.get("up", [])
        header = [layer.label, "Verifies"] + [f"↑ {self.cfg.layers[u].label}" for u in up] + ["↑ Source"]
        rows, untagged = [], 0
        for n in self.g.layer_nodes(layer.id):
            direct = sorted(self.g.parents(n), key=lambda k: self.g.show(k))
            if not direct:
                untagged += 1
                continue
            anc = self.g.ancestors(n.key)
            srcs = sorted({self.g.source(self.g.nodes[k]) for u in up for k in anc.get(u, [])} - {""})
            rows.append([n.label, ", ".join(self.g.show(k) for k in direct)]
                        + [self._list(u, anc.get(u, [])) for u in up]
                        + ["; ".join(srcs) or "—"])
        note = (f"\n{untagged} {layer.label.lower()} file(s) carry no "
                f"`{layer.ref_marker or 'trace'}` link yet and are not listed.\n") if untagged else ""
        return table(header, rows) + note

    def _summary(self, b: dict) -> str:
        rows = []
        for lid, layer in self.cfg.layers.items():
            nodes = self.g.layer_nodes(lid)
            if not nodes:
                continue
            if layer.require:
                ok = sum(1 for n in nodes if not any(
                    f.subject == n.key and f.rule == "MISSING-UPSTREAM" for f in self.findings))
                rows.append([f"{layer.label} with required upstream links", f"{ok} / {len(nodes)}"])
            else:
                rows.append([f"{layer.label} defined", str(len(nodes))])
        for c in self.cfg.coverage:
            nodes = self.g.layer_nodes(c["from"])
            hit = sum(1 for n in nodes if self.g.descendants(n.key).get(c["to"]))
            rows.append([f"{self.cfg.layers[c['from']].label} reaching ≥ 1 {self.cfg.layers[c['to']].label}",
                         f"{hit} / {len(nodes)}"])
        counts = {s: sum(1 for f in self.findings if f.severity == s) for s in ("P0", "P1", "P2", "P3")}
        rows.append(["Findings (P0 / P1 / P2 / P3)", " / ".join(str(v) for v in counts.values())])
        return table(["Check", "Result"], rows) + "\nRun `rtm check` for the itemised findings.\n"
